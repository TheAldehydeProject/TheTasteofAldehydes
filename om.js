  function polygonArea(p) {
    let a = 0;
    for (let i = 0; i < p.length; i++) { const q = p[(i + 1) % p.length]; a += p[i][0] * q[1] - q[0] * p[i][1]; }
    return a / 2;
  }
  /** The window's cell nearest seed i: the rectangle cut by the bisector
      to every other seed (a Voronoi cell, by halving). */
  function cellOf(i, seeds, w, h) {
    let poly = [[0, 0], [w, 0], [w, h], [0, h]];
    const [sx, sy] = seeds[i];
    for (let j = 0; j < seeds.length && poly.length; j++) {
      if (j === i) continue;
      const [tx, ty] = seeds[j];
      const nx = tx - sx, ny = ty - sy, mx = (sx + tx) / 2, my = (sy + ty) / 2;
      const side = (p) => (p[0] - mx) * nx + (p[1] - my) * ny;   // <= 0 keeps
      const out = [];
      for (let k = 0; k < poly.length; k++) {
        const p = poly[k], q = poly[(k + 1) % poly.length];
        const a = side(p), b = side(q);
        if (a <= 0) out.push(p);
        if ((a <= 0) !== (b <= 0)) {
          const f = a / (a - b);
          out.push([p[0] + (q[0] - p[0]) * f, p[1] + (q[1] - p[1]) * f]);
        }
      }
      poly = out;
    }
    return poly;
  }

  /** A polygon cut by a straight line: what is on the side of it where
      side(p) <= 0 (Sutherland and Hodgman's clipping, by one edge). */
  function clipBy(poly, side) {
    const out = [];
    for (let k = 0; k < poly.length; k++) {
      const p = poly[k], q = poly[(k + 1) % poly.length];
      const a = side(p), b = side(q);
      if (a <= 0) out.push(p);
      if ((a <= 0) !== (b <= 0)) {
        const f = a / (a - b);
        out.push([p[0] + (q[0] - p[0]) * f, p[1] + (q[1] - p[1]) * f]);
      }
    }
    return out;
  }
  /** THE BROKEN PANE's pieces: for each blow, its radial cracks — points
      out along each at every ring, wandering a little — and its pieces
      between two of them and two rings (or, where a ring is not cracked
      there, more than two); at the blow itself, the crushed pieces
      between two radial cracks and the first ring, some fallen out. Each
      blow's pieces are kept to its own side of the line between it and the
      next, and to the window. */
  function brokenPanes(w, h, blows) {
    const D = Math.hypot(w, h) * 0.5;
    const out = [];
    blows.forEach((b, bi) => {
      const P = [w * b.x, h * b.y];
      const S = b.spokes, R = b.rings.length;
      const turn = random() * Math.PI * 2;
      // The radial cracks: angle j, and its point at ring k.
      const at = [];
      for (let j = 0; j < S; j++) {
        let a = ((j + 0.5 + (random() - 0.5) * 0.62) / S) * Math.PI * 2 + turn;
        const pts = [];
        for (let k = 0; k < R; k++) {
          a += (random() - 0.5) * 2 * BREAK_WANDER * (k ? 1 : 0.4);
          const r = b.rings[k] * D * (k === R - 1 ? 1 : between(0.86, 1.14));
          pts.push([P[0] + Math.cos(a) * r, P[1] + Math.sin(a) * r]);
        }
        at.push(pts);
      }
      // Which stretches of which rings are cracked: the first always (it is
      // the edge of the crushed glass), the last always (it is past the
      // window), the rest not always.
      const keep = (j, k) => k === 0 || k === R - 1 || random() > BREAK_RING_GAP;
      // Kept to this blow's side of the line between it and each other
      // blow, `toward` of the way to it (or the other's share back).
      const sides = blows.filter((o) => o !== b).map((o) => {
        const Q = [w * o.x, h * o.y];
        const t = b.toward != null ? b.toward : 1 - (o.toward != null ? o.toward : 0.5);
        const M = [P[0] + (Q[0] - P[0]) * t, P[1] + (Q[1] - P[1]) * t];
        const nx = Q[0] - P[0], ny = Q[1] - P[1];
        return (p) => (p[0] - M[0]) * nx + (p[1] - M[1]) * ny;
      });
      const cut = (poly) => {
        sides.forEach((side) => { if (poly.length) poly = clipBy(poly, side); });
        [(p) => -p[0], (p) => -p[1], (p) => p[0] - w, (p) => p[1] - h].forEach((side) => { if (poly.length) poly = clipBy(poly, side); });
        return poly;
      };
      // The crushed glass at the blow: two radial cracks' worth to a piece,
      // and BREAK_HOLE of them gone.
      const gone = new Set();
      while (gone.size < Math.min(BREAK_HOLE, Math.floor(S / 2))) gone.add(Math.floor(random() * Math.floor(S / 2)));
      for (let j = 0; j + 1 < S + 1; j += 2) {
        const j1 = j, j2 = Math.min(j + 1, S - 1), j3 = (j + 2) % S;
        const poly = j2 === j1 ? [P, at[j1][0], at[j3][0]] : [P, at[j1][0], at[j2][0], at[j3][0]];
        if (gone.has(j / 2)) continue;
        const c = cut(poly);
        if (c.length >= 3) out.push({ poly: c, blow: bi, ring: 0 });
      }
      // The pieces out from it.
      for (let j = 0; j < S; j++) {
        const A = at[j], B = at[(j + 1) % S];
        let from = 0;
        for (let k = 1; k < R; k++) {
          if (!keep(j, k)) continue;
          const poly = [];
          for (let q = from; q <= k; q++) poly.push(A[q]);
          for (let q = k; q >= from; q--) poly.push(B[q]);
          const c = cut(poly);
          if (c.length >= 3) out.push({ poly: c, blow: bi, ring: from + 1 });
          from = k;
        }
      }
    });
    return out;
  }

  /** THE RINGS' pieces: the disc round the middle, and each band out from
      it cut into its petals — an arc out and an arc back, a point every
      RING_ARC degrees — each kept to the window. */
  function ringPanes(w, h) {
    const D = Math.hypot(w, h) * 0.5, cx = w / 2, cy = h / 2;
    const parts = w < 700 ? RING_PARTS_NARROW : RING_PARTS;
    const arc = (r, a0, a1) => {
      const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / (RING_ARC * Math.PI / 180)));
      const out = [];
      for (let i = 0; i <= n; i++) { const a = a0 + (a1 - a0) * (i / n); out.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]); }
      return out;
    };
    const toWindow = (poly) => {
      [(p) => -p[0], (p) => -p[1], (p) => p[0] - w, (p) => p[1] - h].forEach((side) => { if (poly.length) poly = clipBy(poly, side); });
      return poly;
    };
    const out = [];
    let offset = random() * Math.PI * 2;
    RING_RADII.forEach((share, k) => {
      const r1 = share * D, r0 = k ? RING_RADII[k - 1] * D : 0;
      const n = parts[k];
      if (n <= 1) {
        const poly = toWindow(arc(r1, 0, Math.PI * 2).slice(0, -1));
        if (poly.length >= 3) out.push({ poly, band: k, mid: r1 * 0.6 });
        return;
      }
      const step = (Math.PI * 2) / n;
      offset += step / 2;                                   // a half step round from the band inside
      const cuts = [];
      for (let j = 0; j < n; j++) cuts.push(offset + j * step + (random() - 0.5) * step * 0.24);
      for (let j = 0; j < n; j++) {
        const a0 = cuts[j], a1 = j + 1 < n ? cuts[j + 1] : cuts[0] + Math.PI * 2;
        const poly = toWindow(arc(r1, a0, a1).concat(arc(r0, a1, a0)));
        if (poly.length >= 3) out.push({ poly, band: k, mid: (r0 + r1) / 2 });
      }
    });
    return out;
  }

  /** THE SPLIT'S GAP: its broken pieces — random polygons, most of them
      small, a few larger, each a few corners at uneven angles and uneven
      reaches, a flake turning in three dimensions — and its specks, and
      three cracks far down; each AT A DEPTH OF ITS OWN (THE DEPTH), drifting
      and swaying on clocks of their own. Laid down a span a little taller
      than the screen, and wrapped round it as they go; the pieces kept
      farthest first, the order they are drawn in. */
  function gapOf(w, h, push) {
    const cx = w / 2, span = h + 200;
    const n = Math.round(push * 2 * span * GAP_SHARDS);
    // Most small, a few large — the largest larger the wider the gap.
    const most = clamp(push * 0.3, 17, 40);
    const shards = [];
    // Which stay once the page is whole: an even share, by order, as many
    // as the page holds at CALM_SHARDS and CALM_MOTES.
    const kept = (i, share) => ((i + 1) * 0.6180339887) % 1 < share;
    const keepShards = Math.min(1, (w * span * CALM_SHARDS) / Math.max(1, n));
    for (let i = 0; i < n; i++) {
      const r = 3.5 + Math.pow(random(), 2.2) * most;
      const corners = 3 + Math.floor(random() * 4);
      const angles = [];
      for (let k = 0; k < corners; k++) angles.push(random() * Math.PI * 2);
      angles.sort((a, b) => a - b);
      shards.push(drifter({
        u: random() * 2 - 1, z: Math.pow(random(), 0.85), fall: between(-7, 7), sway: between(2, 7),
        pts: angles.map((a) => [Math.cos(a) * r * between(0.4, 1), Math.sin(a) * r * between(0.4, 1)]),
        // Its turn in three dimensions, and how quickly each way.
        ax: random() * Math.PI * 2, ay: random() * Math.PI * 2, az: random() * Math.PI * 2,
        wx: between(-0.32, 0.32), wy: between(-0.32, 0.32), wz: between(-0.16, 0.16), way: random() < 0.5 ? -1 : 1,
        ink: between(0.35, 0.8), fill: random() < 0.55 ? between(0.05, 0.16) : 0, bright: random() < 0.1, keep: kept(i, keepShards),
      }, span));
    }
    shards.sort((a, b) => b.z - a.z);
    const motes = [];
    const m = Math.round(push * 2 * span * GAP_MOTES);
    const keepMotes = Math.min(1, (w * span * CALM_MOTES) / Math.max(1, m));
    for (let i = 0; i < m; i++) {
      motes.push(drifter({
        u: random() * 2 - 1, z: random(), fall: between(-16, -3), sway: between(1.5, 9),
        size: between(0.8, 1.9), base: between(0.3, 0.85), keep: kept(i, keepMotes),
      }, span));
    }
    // The cracks, far down, each at its depth — broken into runs, a fissure
    // seen here and there (whole, they read as rails down the gap).
    const cracks = [0.6, 0.8, 0.95].map((z) => {
      const pts = [], on = [];
      let u = (random() - 0.5) * 0.9, run = 0;
      for (let y = -10; y <= span + 30; y += between(16, 34)) {
        u = clamp(u + (random() - 0.5) * 0.35, -0.85, 0.85);
        if (--run < 0) run = Math.floor(between(2, 9)) * (random() < 0.42 ? -1 : 1);
        pts.push(u, y);
        on.push(run >= 0);
      }
      return drifter({ u: 0, z, fall: 0, sway: 0, pts, on, keep: true }, span);
    });
    return { cx, push, span, shards, motes, cracks, alpha: 1, calm: 0, calmK: 1, stirK: 0, calmAt: 0, goneAt: 0 };
  }
  /** What every drifting thing in the gap carries: where it is laid, how
      it sways, how far the hand has moved it — and, from its depth, how
      small and faint it is drawn, how much of the scroll carries it (open,
      and once whole) and how quickly it catches the scroll up (`f`, the
      scroll as it has felt it, through two stages, so it sets off
      smoothly; `c`, how far that has carried it, gathered as it goes, so
      its share can change without it jumping). */
  function drifter(o, span) {
    const z = o.z, sy = window.scrollY || 0, rate = RATE_NEAR + (RATE_FAR - RATE_NEAR) * z;
    return Object.assign(o, { y: random() * span, fq: between(0.15, 0.55), ph: random() * Math.PI * 2,
      ox: 0, oy: 0, vx: 0, vy: 0, lit: 0, X: 0, Y: 0, f: sy, f1: sy,
      p: 1 / (1 + z * DEPTH), fog: 1 - FOG * z, near: 1 - z,
      rate, calmRate: CALM_RATE[0] + (CALM_RATE[1] - CALM_RATE[0]) * z, rn: rate, c: sy * rate,
      tau: (FOLLOW_NEAR + (FOLLOW_FAR - FOLLOW_NEAR) * z) / 2,
      wide: WIDE_NEAR + (WIDE_FAR - WIDE_NEAR) * z });
  }
  /** The gap's things moved on a frame: each catching the scroll up as
      its depth says and carried by its share of it, drifting and swaying,
      and given way to the hand — pushed off it and coming back, lit as it
      passes, the nearer the more — and turned, the faster the page is
      scrolled the faster. `spread` is how far from the middle of the page
      the gap reaches either way; `calm`, how far the page has come together
      (THE PIECES ONCE IT IS WHOLE). */
  function moveGap(g, t, dt, spread, hx, hy, calm) {
    const sy = window.scrollY, span = g.span, cx = g.cx;
    const hand = hx > -9000 && !REDUCE, R2 = GAP_REACH * GAP_REACH;
    g.calm = calm;
    g.calmK = 1 - (1 - CALM_STIR) * calm;
    g.stirK = stir * g.calmK;
    const stirK = g.stirK, shove = 2600 * (1 - (1 - CALM_HAND) * calm), all = cx * CALM_WIDE;
    const step = (s, still) => {
      const was = s.f;
      if (REDUCE) { s.f = s.f1 = sy; }
      else {
        const k = 1 - Math.exp(-dt / s.tau);
        s.f1 += (sy - s.f1) * k;
        s.f += (s.f1 - s.f) * k;
        if (hand && !still) {
          const dx = s.X - hx, dy = s.Y - hy, d2 = dx * dx + dy * dy;
          if (d2 < R2 && d2 > 0.01) {
            const d = Math.sqrt(d2), f = 1 - d / GAP_REACH, push = f * f * shove * dt * (0.35 + 0.65 * s.near);
            s.vx += (dx / d) * push; s.vy += (dy / d) * push;
            if (f > s.lit) s.lit = f;
          }
        }
        s.vx += (-s.ox * 16 - s.vx * 5.5) * dt;
        s.vy += (-s.oy * 16 - s.vy * 5.5) * dt;
        s.ox += s.vx * dt; s.oy += s.vy * dt;
        s.lit *= Math.exp(-dt * 2.2);
      }
      s.rn = s.rate + (s.calmRate - s.rate) * calm;
      s.c += (s.f - was) * s.rn;
      let y = s.y + (REDUCE ? 0 : t * s.fall * s.p) - s.c;
      y = ((y % span) + span) % span - 100;
      const reach = spread * s.wide + (all - spread * s.wide) * calm;
      s.X = cx + s.u * (reach + stirK * SCROLL_SPREAD * s.p) + (REDUCE ? 0 : Math.sin(t * s.fq * Math.PI * 2 + s.ph) * s.sway * s.p) + s.ox;
      s.Y = y + s.oy;
    };
    const tumble = stirK * SCROLL_TUMBLE;
    g.shards.forEach((s) => {
      step(s);
      if (REDUCE) return;
      const more = tumble * s.way * (0.4 + 0.6 * s.near);
      s.ax += (s.wx + more * 0.7) * dt;
      s.ay += (s.wy + more * 0.5) * dt;
      s.az += (s.wz + more * 0.3) * dt;
    });
    g.motes.forEach((s) => step(s));
    g.cracks.forEach((s) => step(s, true));
  }
  /** The gap's things where they are, at a strength `a`. With `walls` —
      while the gap is open, on its own canvas under the halves' ground —
      the light far down first and the walls' shade over all of it last:
      the walls standing at `walls.l` and `walls.r` across the window. The
      light lies across the whole of the gap wherever the walls stand, and
      each wall's shade goes with that wall: the halves parting only
      uncover what lies there (2026-10-15; the two were drawn between the
      walls wherever they stood, so as the halves parted the gap's light
      was stretched out with them). */
  function drawGap(g, t, a, walls) {
    const L = LIGHT, Ln = Math.hypot(L[0], L[1], L[2]);
    const lx = L[0] / Ln, ly = L[1] / Ln, lz = L[2] / Ln;
    // THE LIGHT FAR DOWN: the faintest gold up the middle of the gap.
    if (walls) laidDown(backdropFor().glow, { l: g.cx - g.push, r: g.cx + g.push }, a);
    // THE CRACKS, far down: narrowed by their depth, faint, carried by
    // little of the scroll.
    ink.lineWidth = 1;
    ink.strokeStyle = rgba(LINE, 1);
    const reach = g.push, calm = g.calm, stirK = g.stirK;
    const flex = REDUCE ? 0 : stirK * SCROLL_FLEX;
    g.cracks.forEach((c, ci) => {
      if (calm > 0.997) return;
      ink.globalAlpha = 0.34 * c.fog * a * (1 - calm);
      const off = c.Y + 100;                    // (how far it has been carried, wrapped)
      [off - g.span, off].forEach((k) => {
        ink.beginPath();
        for (let i = 0; i < c.pts.length; i += 2) {
          const Y = c.pts[i + 1] + k - 100;
          const X = g.cx + c.pts[i] * reach * c.wide + (flex ? Math.sin(Y / 90 + t * 2.2 + ci * 2.1) * flex * c.p : 0);
          if (i && c.on[i / 2]) ink.lineTo(X, Y); else ink.moveTo(X, Y);
        }
        ink.stroke();
      });
    });
    // THE PIECES, farthest first: each a flake turned in three dimensions
    // (turned about x, then y, then z), drawn as it faces the window — the
    // more it faces the light, the brighter, and a glint as it comes round
    // to face it squarely.
    ink.fillStyle = rgba(LINE, 1);
    g.shards.forEach((s) => {
      if (s.Y < -60 || s.Y > H + 60) return;
      const kept = s.keep ? 1 : 1 - calm;
      if (kept < 0.003) return;
      const ca = Math.cos(s.ax), sa = Math.sin(s.ax), cb = Math.cos(s.ay), sb = Math.sin(s.ay), cc = Math.cos(s.az), sc = Math.sin(s.az);
      const k = s.p;
      const m00 = cc * cb * k, m01 = (cc * sb * sa - sc * ca) * k;
      const m10 = sc * cb * k, m11 = (sc * sb * sa + cc * ca) * k;
      const nx = cc * sb * ca + sc * sa, ny = sc * sb * ca - cc * sa, nz = cb * ca;
      const lit = Math.abs(nx * lx + ny * ly + nz * lz);
      ink.beginPath();
      s.pts.forEach(([px, py], j) => {
        const X = s.X + m00 * px + m01 * py, Y = s.Y + m10 * px + m11 * py;
        if (j) ink.lineTo(X, Y); else ink.moveTo(X, Y);
      });
      ink.closePath();
      const hot = 1 + 1.1 * Math.max(s.lit, stirK * SCROLL_LIT * s.near);
      const k2 = a * s.fog * hot * kept;
      if (s.fill) { ink.globalAlpha = Math.min(1, s.fill * (0.25 + 0.95 * lit) * k2); ink.fill(); }
      ink.globalAlpha = Math.min(1, s.ink * (s.bright ? 1.35 : 1) * (0.45 + 0.55 * lit) * k2);
      ink.strokeStyle = rgba(LINE, 1);
      ink.stroke();
      const glint = Math.pow(lit, GLINT);
      if (glint > 0.04) {
        ink.globalAlpha = Math.min(1, glint * 0.9 * k2);
        ink.strokeStyle = rgba(SECOND, 1);
        ink.stroke();
      }
    });
    // The specks: smaller and fainter the farther, each drawn out into a
    // short streak along the way the page is being scrolled — the faster
    // and the nearer the longer, by degrees, a dot at rest.
    ink.globalCompositeOperation = "lighter";
    ink.fillStyle = rgba(SPECK, 1);
    const streak = REDUCE ? 0 : scrollV * 0.012 * g.calmK;
    g.motes.forEach((s) => {
      if (s.Y < -20 || s.Y > H + 20) return;
      const kept = s.keep ? 1 : 1 - calm;
      if (kept < 0.003) return;
      const tw = REDUCE ? 1 : 0.75 + 0.25 * Math.sin(t * 1.7 + s.ph * 3);
      ink.globalAlpha = Math.min(1, s.base * tw * a * s.fog * kept * (1 + 1.6 * Math.max(s.lit, stirK * SCROLL_LIT * s.near)));
      const z = Math.max(0.6, s.size * (0.4 + 0.6 * s.p)), L = streak * s.rn;
      ink.fillRect(s.X - z / 2, (L < 0 ? s.Y + L : s.Y) - z / 2, z, Math.abs(L) + z);
    });
    ink.globalCompositeOperation = "source-over";
    ink.globalAlpha = 1;
    ink.lineWidth = 1;
    // THE WALLS' SHADE: the void drawn over the gap from each edge inward,
    // so what lies near a wall seems to go in under the page.
    if (walls) shadeWalls(g, walls, a);
  }
  /** THE GAP'S LIGHT AND SHADE, as two pictures a band of the gap tall —
      the light far down and the walls' shade — worked out a pixel at a
      time, each pixel's strength a little off at random (dithered): as a
      gradient, so faint a light on so dark a ground came out in visible
      steps, stripes down the gap. Laid down the gap one band under the
      next, as wide as the gap is — made as wide as the gap opens, so it is
      never stretched far. */
  const BAND = 256, BAND_SIDE = 30;
  let backdrop = null;
  function backdropFor() {
    const r = Math.min(ratio, 2), wide = Math.max(240, Math.round(gap ? gap.push * 2 : 240));
    if (backdrop && backdrop.r === r && backdrop.wide === wide) return backdrop;
    const pw = Math.ceil((wide + BAND_SIDE * 2) * r), ph = Math.ceil(BAND * r);
    const make = (at) => {
      const c = document.createElement("canvas");
      c.width = pw; c.height = ph;
      const g = c.getContext("2d"), img = g.createImageData(pw, ph), d = img.data;
      for (let x = 0; x < pw; x++) {
        const u = (x / r - BAND_SIDE) / wide;               // 0 at the left wall, 1 at the right
        const [rgb, a] = at(u);
        for (let y = 0; y < ph; y++) {
          const k = (y * pw + x) * 4;
          d[k] = rgb[0]; d[k + 1] = rgb[1]; d[k + 2] = rgb[2];
          d[k + 3] = clamp(Math.round(a * 255 + Math.random() - 0.5), 0, 255);
        }
      }
      g.putImageData(img, 0, 0);
      return c;
    };
    const glow = make((u) => [LINE, u < 0 || u > 1 ? 0 : DEEP_GLOW * Math.exp(-Math.pow((u - 0.5) / 0.26, 2))]);
    const shade = make((u) => {
      const d = Math.min(u, 1 - u) / (WALL_REACH / 2);       // 0 at a wall, 1 WALL_REACH of the half width in
      const k = d <= 0 ? 1 : d >= 1 ? 0 : d < 0.45 ? 1 - (1 - 0.32) * (d / 0.45) : 0.32 * Math.pow(1 - (d - 0.45) / 0.55, 2);
      return [[6, 5, 9], WALL_SHADE * k];
    });
    backdrop = { r, glow, shade, wide };
    return backdrop;
  }
  function laidDown(img, walls, a) {
    const k = Math.max(1, walls.r - walls.l) / backdrop.wide;
    const x = walls.l - BAND_SIDE * k, w = img.width / backdrop.r * k;
    ink.globalAlpha = clamp(a, 0, 1);
    for (let y = -20; y < H + 20; y += BAND) ink.drawImage(img, x, y, w, BAND);
    ink.globalAlpha = 1;
  }
  /** The walls' shade, made for the whole width of the gap and cut down its
      middle, the left half laid at the left wall and the right at the
      right — each moving with its wall, never stretched. */
  function shadeWalls(g, walls, a) {
    const img = backdropFor().shade, r = backdrop.r, k = (g.push * 2) / backdrop.wide;
    const cut = Math.round((BAND_SIDE + backdrop.wide / 2) * r);
    const lw = (cut / r) * k, rw = ((img.width - cut) / r) * k;
    ink.globalAlpha = clamp(a, 0, 1);
    for (let y = -20; y < H + 20; y += BAND) {
      ink.drawImage(img, 0, 0, cut, img.height, walls.l - BAND_SIDE * k, y, lw, BAND);
      ink.drawImage(img, cut, 0, img.width - cut, img.height, walls.r - rw + BAND_SIDE * k, y, rw, BAND);
    }
    ink.globalAlpha = 1;
  }
  /** The page's flow, copied whole, without an id, a tab stop or anything
      else that could be found or reached. */
  function copyFlow() {
    const flow = document.createElement("div");
    flow.className = "human-page om-page om-flow";
    flowParts().forEach((el) => flow.appendChild(el.cloneNode(true)));
    return scrub(flow);
  }
  const flowParts = () => [...document.querySelectorAll("body > main, body > .house-credit, body > .human-foot")];
  /** A copy made unfindable and unreachable: no ids, no labels by id, no tab stops. */
  function scrub(el) {
    const all = [el].concat([...el.querySelectorAll("*")]);
    all.forEach((e) => {
      if (e.hasAttribute("id")) e.removeAttribute("id");
      if (e.hasAttribute("aria-labelledby")) e.removeAttribute("aria-labelledby");
      if (e.matches("a, button, summary, input, [tabindex]")) e.setAttribute("tabindex", "-1");
    });
    return el;
  }

  /** THE PIECES FOLLOW THE PAGE (2026-10-13 — "whenever you click on
      anything, the glass gets fixed and it is buggy ... When you click on
      the perfumes, the break should not be fixed"). Each piece holds a copy
      of the page, so a fragrance opened under the break used to have to
      mend it first — the copies would have gone on showing it shut — and
      the press was held while it mended and given back after, which was
      the bug. Now every change to the page is made to every copy too, as
      it happens: an attribute (a fragrance's `open`, the measured height
      and fade house.js opens it with, a class) set on the same element of
      each copy, so its opening runs in the pieces in step with the page;
      anything added or taken away (the notes' buttons, a window's text)
      copied over whole. An element is found in a copy by where it stands —
      the same child of the same child — since the copies are the page's
      own shape. */
  const MIRRORED_NOT = new Set(["id", "tabindex", "aria-labelledby"]);
  let mirror = null;
  function pathOf(node, tops) {
    const path = [];
    for (let n = node; n; n = n.parentElement) {
      const top = tops.indexOf(n);
      if (top >= 0) { path.unshift(top); return path; }
      if (!n.parentElement) return null;
      path.unshift(Array.prototype.indexOf.call(n.parentElement.children, n));
    }
    return null;
  }
  function inCopy(copy, path) {
    let n = copy.children[path[0]];
    for (let i = 1; n && i < path.length; i++) n = n.children[path[i]];
    return n || null;
  }
  function followPage(copies) {
    const tops = flowParts();
    mirror = new MutationObserver((records) => {
      const whole = [];
      records.forEach((r) => {
        const el = r.type === "characterData" ? r.target.parentElement : r.target;
        if (!el || !el.isConnected) return;
        if (r.type === "attributes") {
          if (MIRRORED_NOT.has(r.attributeName)) return;
          const path = pathOf(el, tops);
          if (!path) return;
          const v = el.getAttribute(r.attributeName);
          copies().forEach((copy) => {
            const twin = inCopy(copy, path);
            if (!twin) return;
            if (v === null) twin.removeAttribute(r.attributeName);
            else if (twin.getAttribute(r.attributeName) !== v) twin.setAttribute(r.attributeName, v);
          });
        } else if (!whole.some((w) => w.contains(el))) {
          for (let i = whole.length - 1; i >= 0; i--) if (el.contains(whole[i])) whole.splice(i, 1);
          whole.push(el);
        }
      });
      whole.forEach((el) => {
        const path = pathOf(el, tops);
        if (!path) return;
        copies().forEach((copy) => {
          const twin = inCopy(copy, path);
          if (twin) twin.replaceWith(scrub(el.cloneNode(true)));
        });
      });
    });
    tops.forEach((el) => mirror.observe(el, { attributes: true, childList: true, characterData: true, subtree: true }));
  }

  /** The page's own stylesheet, as the page asks for it — by its version —
      for the copies' shadow roots, so they are styled as the page is and
      never by an older copy a browser has kept. */
  function sheetHref() {
    const own = document.querySelector('link[rel="stylesheet"][href*="style.css"]');
    return own ? own.href : (window.SITE_ROOT || "") + "style.css";
  }

  // ============================================================
  // THE SPLIT (see SPLIT_PUSH): the page's two halves, each a copy of the
  // whole page laid in the page itself and cut along the one edge (THE
  // EDGES), pushed apart — and under each, laid in the page too and moved
  // with it, its GROUND: the page's own colour cut along the same edge,
  // with the gold seam along it. Between the grounds and the writing, the
  // page's own canvas (THE WORD, and the drawing once OM is pressed); under
  // the grounds, the gap's own canvas. The halves and their grounds are
  // moved by one transform each and the seams' gold by its opacity —
  // opening and closing by the browser's own clock, all six on one start
  // time. (Until 2026-10-14 the drawing behind was cut with the page on two
  // canvases fixed to the window, the page's ground drawn in them and cut
  // where the page stood each frame: on a phone, which scrolls the page a
  // little ahead of what a script can draw, the ground's edge trailed the
  // writing's.)
  // ============================================================
  let halves = null;
  let scrollV = 0, lastScroll = null;      // the page's scrolling, px a second (eased)
  let stir = 0;                            // how stirred the gap's geometry is by it, 0 to 1
  let waveFrom = 0;                        // when the halves met (ms): THE WAVE from then
  let waveNow = null;                      // where it is this frame, for the specks
  let worldIn = 1;                         // how much of the drawing behind is there (THE BACKGROUND WAITING)
  let word = null;                         // what the word is this frame, for the tests
  const smoother = (u) => u * u * u * (u * (u * 6 - 15) + 10);    // at rest at both ends
  const smooth01 = (u) => { u = clamp(u, 0, 1); return u * u * (3 - 2 * u); };

  /** THE EDGES (see EDGE_WANDER) for a gap of `push` either way: the line
      the page broke along, as points down the page, [y] and [x] from the
      middle of the page — each half cut along it, the left keeping what is
      to its left and the right what is to its right (so `L` and `R` are
      the one line). */
  function edgesFor(push) {
    const k = clamp(push / 100, 0.3, 1.2);
    const line = { ys: [], xs: [], deep: random() < 0.5, walk: 0 };
    const e = { A: EDGE_WANDER * k, T: EDGE_TOOTH * k,
      ph: [random(), random(), random()].map((v) => v * Math.PI * 2), L: line, R: line, to: -300 };
    e.reach = Math.ceil(e.A * 2.3 + e.T * 2.6) + 3;
    return e;
  }
  /** Laid on down the page to `to`. */
  function growEdges(e, to) {
    const s = e.L;
    let y = s.ys.length ? s.ys[s.ys.length - 1] : -300;
    while (y < to) {
      y += between(EDGE_PITCH[0], EDGE_PITCH[1]);
      s.deep = !s.deep;
      s.walk = clamp(s.walk * 0.86 + (random() * 2 - 1) * e.A * 0.35, -e.A * 1.2, e.A * 1.2);
      const wander = e.A * (0.55 * Math.sin(y / 297 + e.ph[0]) + 0.3 * Math.sin(y / 131 + e.ph[1]) + 0.15 * Math.sin(y / 61 + e.ph[2]));
      const tooth = e.T * (random() < EDGE_JOG ? between(1.6, 2.6) : between(0.25, 1));
      s.ys.push(y);
      s.xs.push(wander + s.walk + (s.deep ? tooth : -tooth));
    }
    e.to = to;
  }
  function lowerBound(a, v) {
    let lo = 0, hi = a.length;
    while (lo < hi) { const mid = (lo + hi) >> 1; if (a[mid] < v) lo = mid + 1; else hi = mid; }
    return lo;
  }
  /** A half's edge at a height down its page, from the middle of the page. */
  function edgeAt(s, y) {
    const i = lowerBound(s.ys, y);
    if (i <= 0) return s.xs[0];
    if (i >= s.ys.length) return s.xs[s.xs.length - 1];
    const f = (y - s.ys[i - 1]) / (s.ys[i] - s.ys[i - 1]);
    return s.xs[i - 1] + (s.xs[i] - s.xs[i - 1]) * f;
  }
  /** A half's cut, for the stylesheet: everything on its side of the edge,
      down the whole of the page and well past it — and, for a ground,
      `grow` px past the edge (so two grounds together leave no hairline of
      the void between them) and `dy` px lower (a ground reaches above the
      page). */
  function clipOf(s, left, w, grow, dy) {
    // (On the copy of the page in the half, which is laid out as the page
    // is — not on the half that moves, where a cut would be a mask laid
    // again every frame it moves: painted into the copy once, it moves
    // with it for nothing. And so on a ground.)
    grow = grow || 0; dy = dy || 0;
    const at = w / 2 + (left ? grow : -grow), P = 800, FAR = 400000, out = [], n = s.ys.length;
    const outer = (left ? -P : w + P) + "px";
    out.push(outer + " " + -P + "px", (at + s.xs[0]).toFixed(1) + "px " + -P + "px");
    for (let i = 0; i < n; i++) out.push((at + s.xs[i]).toFixed(1) + "px " + (s.ys[i] + dy).toFixed(1) + "px");
    out.push((at + s.xs[n - 1]).toFixed(1) + "px " + FAR + "px", outer + " " + FAR + "px");
    return "polygon(" + out.join(",") + ")";
  }
  /** The seam's line, for its picture: the edge `x0` px from the picture's
      left, `dy` px lower than the page. */
  function seamLine(s, x0, dy) {
    const out = [];
    for (let i = 0; i < s.ys.length; i++) out.push((i ? "L" : "M") + (x0 + s.xs[i]).toFixed(1) + " " + (s.ys[i] + dy).toFixed(1));
    return out.join("");
  }
  function setClips() {
    const e = halves.edges, w = copyWidth;
    [[halves.copies[0], e.L, true, 0, 0], [halves.copies[1], e.R, false, 0, 0],
      [halves.fills[0], e.L, true, 0.6, GROUND_TOP], [halves.fills[1], e.R, false, 0.6, GROUND_TOP]].forEach(([el, s, left, grow, dy]) => {
      const c = clipOf(s, left, w, grow, dy);
      el.style.clipPath = c;
      el.style.webkitClipPath = c;
    });
    const d = seamLine(e.L, e.reach + 4, GROUND_TOP);
    halves.seams.forEach((svg) => svg.querySelectorAll("path").forEach((p) => p.setAttribute("d", d)));
  }
  /** Each half's box only as wide as its side of the page and the reach
      of its edge — so neither is drawn, or laid over the other, where it
      is not seen — and its ground's the same; each seam's picture just
      wide enough for the edge. */
  function sizeHalves() {
    const w = copyWidth, m = w / 2, reach = halves.edges.reach, [l, r] = halves.text, [gl, gr] = halves.grounds;
    l.style.width = gl.style.width = (m + reach) + "px";
    r.style.left = gr.style.left = (m - reach) + "px";
    r.style.width = gr.style.width = (w - m + reach) + "px";
    halves.copies.forEach((c) => { c.style.width = w + "px"; });
    halves.copies[1].style.marginLeft = -(m - reach) + "px";
    halves.fills.forEach((f) => { f.style.width = w + "px"; });
    halves.fills[0].style.left = "0px";
    halves.fills[1].style.left = -(m - reach) + "px";
    halves.seams.forEach((svg, k) => {
      svg.style.left = (k ? -4 : m - reach - 4) + "px";
      svg.setAttribute("width", 2 * reach + 8);
    });
  }
  /** The grounds as tall as the page (and GROUND_TOP above it) — never
      taller, or the page would scroll on past its end. */
  function fitGround() {
    const tall = Math.ceil(halves.text[0].offsetHeight + GROUND_TOP);
    if (tall === halves.tall) return;
    halves.tall = tall;
    halves.groundHost.style.height = tall + "px";
    halves.grounds.forEach((g) => { g.style.height = tall + "px"; });
    halves.fills.forEach((f) => { f.style.height = tall + "px"; });
    halves.seams.forEach((svg) => svg.setAttribute("height", tall));
  }
  /** How far down the edges must be laid: the page's length, and more. */
  const edgeLength = () => Math.max(halves.text[0].offsetHeight, root.scrollHeight) + 2500;

  /** THE SHAKE, k px at its hardest, tt seconds in: a tremor, each half
      trembling on its own — and, as far as `one` says, the two as one. */
  function tremble(k, tt, one) {
    if (!k) return { xl: 0, xr: 0, yl: 0, yr: 0 };
    const w = tt * SHAKE_HZ * Math.PI * 2, o = 1 - one;
    const cx = 0.7 * Math.sin(w) + 0.3 * Math.sin(w * 1.63 + 0.7), cy = 0.3 * Math.sin(w * 1.37 + 1.1);
    const lx = 0.7 * Math.sin(w * 1.13 + 1.9) + 0.3 * Math.sin(w * 1.71 + 0.2), ly = 0.3 * Math.sin(w * 1.21 + 2.4);
    const rx = 0.7 * Math.sin(w * 0.91 + 4.1) + 0.3 * Math.sin(w * 1.47 + 2.6), ry = 0.3 * Math.sin(w * 1.53 + 0.4);
    return { xl: k * (cx * one + lx * o), xr: k * (cx * one + rx * o), yl: k * (cy * one + ly * o), yr: k * (cy * one + ry * o) };
  }
  /** Where the halves stand: each half's offset across and up or down, how
      far they have come together (`met`, 0 apart, 1 met), how strongly
      their seams' gold is drawn, how far down the crack has run and how
      strongly it is drawn (`crackA`, on the page's canvas, until the seams
      take over from it). */
  function restAt() {
    const p = halves.push;
    return { l: -p, r: p, yl: 0, yr: 0, met: 0, seam: SEAM_REST, crack: 1, crackA: 0, write: SPLIT_WRITING };
  }
  /** THE OPENING, t ms after the crack sets off (before it, whole). */
  const OPEN_ALL = OPEN_CRACK * 0.6 + OPEN_PART;
  function openPath(t) {
    if (t <= 0) return { l: 0, r: 0, yl: 0, yr: 0, met: 1, seam: 0, crack: 0, crackA: 0, write: 1 };
    const push = halves.push, crack = smoother(clamp(t / OPEN_CRACK, 0, 1));
    const u = clamp((t - OPEN_CRACK * 0.6) / OPEN_PART, 0, 1), apart = smoother(u);
    // The shake from the crack's first moment, hardest as the halves break
    // apart, settling as they come to rest; each half on its own.
    const env = OPEN_SHAKE * smooth01(t / (OPEN_CRACK * 0.6)) * (1 - u) * (1 - u);
    const q = tremble(REDUCE ? 0 : halves.shake * env, t / 1000, 0);
    // The crack runs down on the page's canvas; as it reaches the foot the
    // seams' own gold takes over from it, bright, settling to its rest.
    const over = smooth01((t - OPEN_CRACK * 0.92) / 260);
    const seam = over * (SEAM_REST + (1 - SEAM_REST) * (1 - apart));
    return { l: -push * apart + q.xl, r: push * apart + q.xr, yl: q.yl, yr: q.yr, met: 1 - apart, seam, crack, crackA: 1 - over, write: 1 - (1 - SPLIT_WRITING) * apart };
  }
  /** THE CLOSING, t ms after OM was pressed. */
  function joinPath(t) {
    const u = clamp(t / SPLIT_MS, 0, 1), met = smoother(u), apart = halves.from * (1 - met);
    // The shake from the first moment — coming up out of nothing over
    // SHAKE_RISE, growing as they come, hardest as they meet — dying away
    // after, and still at the end.
    let env;
    if (t <= SPLIT_MS) env = smooth01(t / SHAKE_RISE) * (SHAKE_ON_WAY + (1 - SHAKE_ON_WAY) * u * u * u);
    else {
      const after = t - SPLIT_MS, end = clamp(after / SHAKE_TAIL, 0, 1);
      env = Math.exp(-after / SHAKE_TAU) * (1 - end * end * (3 - 2 * end));
    }
    const q = tremble(REDUCE ? 0 : halves.shake * env, t / 1000, met * met * met);
    // The seams flash gold as the halves meet, and go.
    let seam = SEAM_REST;
    if (t > SPLIT_MS * 0.85) seam = t <= SPLIT_MS ? SEAM_REST + (1 - SEAM_REST) * smooth01((t - SPLIT_MS * 0.85) / (SPLIT_MS * 0.15)) : 1 - smooth01((t - SPLIT_MS) / 600);
    // The writing going as they set off (from the little of it faded while
    // they were apart), and back, whole, as they meet.
    const out = smoother(clamp(t / WRITING_OUT, 0, 1));
    const back = smoother(clamp((t / SPLIT_MS - WRITING_BACK[0]) / (WRITING_BACK[1] - WRITING_BACK[0]), 0, 1));
    return { l: -apart + q.xl, r: apart + q.xr, yl: q.yl, yr: q.yr, met, seam, crack: 1, crackA: 0, write: SPLIT_WRITING * (1 - out) * (1 - back) + back };
  }
  function splitState(now) {
    if (gatherAt) return joinPath(now - gatherAt);
    if (!halves.opened && halves.reverting) return openPath(halves.openAt ? now - halves.openAt : 0);
    return restAt();
  }
  function placeSplit(at) {
    const tl = "translate(" + at.l.toFixed(2) + "px," + at.yl.toFixed(2) + "px)";
    const tr = "translate(" + at.r.toFixed(2) + "px," + at.yr.toFixed(2) + "px)";
    halves.text[0].style.transform = halves.grounds[0].style.transform = tl;
    halves.text[1].style.transform = halves.grounds[1].style.transform = tr;
    halves.seams.forEach((s) => { s.style.opacity = at.seam.toFixed(3); });
    halves.text.forEach((el) => { el.style.opacity = at.write < 1 ? at.write.toFixed(3) : ""; });
  }
  /** Where each half stands now, as drawn: across, and up or down — and
      where the top of the page is on the window. */
  function splitOffsets() {
    const box = halves.host.getBoundingClientRect();
    const a = halves.text[0].getBoundingClientRect(), b = halves.text[1].getBoundingClientRect();
    return { l: a.left - box.left, r: b.left - box.left - (halves.m - halves.edges.reach), yl: a.top - box.top, yr: b.top - box.top, top: box.top };
  }
  /** Which half shows the point (x, y) on the window — "l", "r", or
      neither (the gap) — the halves standing as `at` says. */
  function sideAt(x, y, at) {
    const e = halves.edges, m = halves.m;
    if (x - at.l < m + edgeAt(e.L, y - at.top - at.yl)) return "l";
    if (x - at.r > m + edgeAt(e.R, y - at.top - at.yr)) return "r";
    return null;
  }
  /** The edge on the window, as a path for the page's canvas: the line
      where the page now stands (`top`, the top of the page on the window),
      `dx` across and `dy` down, from `y0` to `y1` on the window. */
  function edgeOnWindow(dx, dy, top, y0, y1, first) {
    const s = halves.edges.L, m = halves.m;
    const i0 = Math.max(0, lowerBound(s.ys, y0 - top - dy) - 1), i1 = Math.min(s.ys.length - 1, lowerBound(s.ys, y1 - top - dy));
    for (let i = i0; i <= i1; i++) {
      const x = m + dx + s.xs[i], y = s.ys[i] + top + dy;
      if (first && i === i0) ink.moveTo(x, y); else ink.lineTo(x, y);
    }
  }
  /** The page's canvas kept to the halves, out of the gap: the gap's shape
      — between the left half's edge and the right half's, where each now
      stands — taken out of what has been drawn. (Once, after the drawing:
      the drawing kept to the halves by a clip instead cost every line and
      speck of it a mask, and held the closing at half its frames.) */
  function eraseGap(at, top) {
    const B = 40, s = halves.edges.L, m = halves.m;
    ink.beginPath();
    edgeOnWindow(at.l, at.yl, top, -B, H + B, true);
    const i0 = Math.max(0, lowerBound(s.ys, -B - top - at.yr) - 1), i1 = Math.min(s.ys.length - 1, lowerBound(s.ys, H + B - top - at.yr));
    for (let i = i1; i >= i0; i--) ink.lineTo(m + at.r + s.xs[i], s.ys[i] + top + at.yr);
    ink.closePath();
    ink.globalCompositeOperation = "destination-out";
    ink.globalAlpha = 1;
    ink.fillStyle = "#000";
    ink.fill();
    ink.globalCompositeOperation = "source-over";
  }
  /** THE CRACK running down the page as it opens, on the page's canvas —
      along each half's edge, where each now stands — to `upTo`, a light at
      its tip, until the seams' own gold takes over. */
  function drawCrack(at, top) {
    if (at.crackA < 0.004 || at.crack <= 0) return;
    const upTo = -40 + (H + 80) * at.crack;
    [[at.l, at.yl], [at.r, at.yr]].forEach(([dx, dy]) => {
      ink.beginPath();
      edgeOnWindow(dx, dy, top, -40, upTo, true);
      ink.strokeStyle = rgba(LINE, 1);
      ink.lineWidth = 3.4;
      ink.globalAlpha = 0.16 * at.crackA;
      ink.stroke();
      ink.lineWidth = 1;
      ink.globalAlpha = 0.9 * at.crackA;
      ink.stroke();
    });
    ink.globalAlpha = 1;
    if (at.crack < 1) {
      const tx = halves.m + at.l + edgeAt(halves.edges.L, upTo - top - at.yl);
      ink.globalCompositeOperation = "lighter";
      const g = ink.createRadialGradient(tx, upTo, 0, tx, upTo, 22);
      g.addColorStop(0, rgba(SECOND, 0.85 * at.crackA));
      g.addColorStop(1, rgba(SECOND, 0));
      ink.fillStyle = g;
      ink.fillRect(tx - 22, upTo - 22, 44, 44);
      ink.globalCompositeOperation = "source-over";
    }
  }
  /** The halves laid out at the page's width. Only the width moves them: a
      phone's bar coming and going changes the height, and the broken
      pieces are scattered down the whole of its screen to begin with. */
  function layoutSplit() {
    const w = page.clientWidth || root.clientWidth;
    const m = w / 2, widthMoved = w !== copyWidth || !(halves.live ? gap : halves.gap);
    copyWidth = w;
    halves.m = m;
    halves.host.style.width = halves.groundHost.style.width = w + "px";
    if (widthMoved) {
      halves.push = Math.round(clamp(w * SPLIT_PUSH, PUSH_LEAST, PUSH_MOST));
      halves.shake = SHAKE * (w < 700 ? 0.66 : 1);
      halves.edges = edgesFor(halves.push);
      sizeHalves();
      growEdges(halves.edges, edgeLength());
      setClips();
    }
    fitGround();
    halves.docTop = halves.host.getBoundingClientRect().top + window.scrollY;
    if (gatherAt) return;
    if (mendButton) mendButton.style.left = m + "px";
    if (!widthMoved) return;
    const laid = gapOf(w, Math.max(H, (window.screen && window.screen.height) || 0), halves.push);
    if (halves.live) gap = laid; else halves.gap = laid;    // (reverted and not yet live: the whole page's kept)
    // A new width under the opening: straight to apart.
    if (halves.opened || halves.anims.length) { halves.opened = false; finishOpen(); }
  }
  /** The split laid over the page: as it opens, already apart and fading
      in (THE PAGE OPENS ALREADY SPLIT); or, `reverting`, over the page
      exactly as it is and whole, and then THE OPENING (REVERT PAGE). */
